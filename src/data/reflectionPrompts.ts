function shuffled<T>(items: T[]) {
  const copy = [...items];
  for (let index = copy.length - 1; index > 0; index -= 1) {
    const target = Math.floor(Math.random() * (index + 1));
    [copy[index], copy[target]] = [copy[target], copy[index]];
  }
  return copy;
}

export function createReflectionSelection(mode: LoveMode, count: number) {
  const pool = reflectionPrompts.filter((prompt) => prompt.mode === mode);
  const buckets = new Map<string, ReflectionPrompt[]>();
  pool.forEach((prompt) => buckets.set(prompt.category, [...(buckets.get(prompt.category) ?? []), prompt]));
  const queues = shuffled([...buckets.values()].map((bucket) => shuffled(bucket)));
  const selected: string[] = [];
  let row = 0;
  while (selected.length < Math.min(count, pool.length)) {
    for (const queue of queues) {
      if (queue[row]) selected.push(queue[row].id);
      if (selected.length >= count) break;
    }
    row += 1;
  }
  return selected;
}

export function getReflectionPrompt(id: string) {
  return reflectionPrompts.find((prompt) => prompt.id === id);
}
