import type { LoveMode } from "./tasks";

export type ReflectionPrompt = {
  id: string;
  mode: LoveMode;
  category: string;
  question: string;
  helper: string;
};

type PromptSeed = [question: string, helper: string];

function group(mode: LoveMode, category: string, seeds: PromptSeed[]): ReflectionPrompt[] {
  return seeds.map(([question, helper], index) => ({
    id: `${mode}-${category}-${index + 1}`,
    mode,
    category,
    question,
    helper,
  }));
}

